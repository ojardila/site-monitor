#!/usr/bin/env python3
"""Give every ojardila site repo its synthetic monitor, automatically.

RULE - a repo is a "site project" when ALL hold:
  * owned by ojardila, not archived, not a fork, not site-monitor itself;
  * no `no-monitor` topic;
  * and EITHER it has the `website` topic, OR its manifests/ (excluding
    overlays/dev) contain a Gateway API `kind: HTTPRoute` exposing a public
    hostname (not *.int.*, not a wildcard, not *.local).
A site repo is COMPLIANT when it has monitor.yaml and
.github/workflows/synthetic-monitor.yml. For non-compliant repos this commits
the missing files to the default branch (author ojardila
<oscar3425@gmail.com>), copies TELEGRAM_BOT_TOKEN / TELEGRAM_CHAT_ID into the
repo when missing (from this repo's secrets), and dispatches a first run.
URL = repo homepage if set, else https://<first public hostname>/. The
generated monitor.yaml checks title + main sections taken from the live page
and is marked `revalidate: true` until a human tightens it. Existing
monitor.yaml files are never overwritten.
"""
import base64, json, os, re, subprocess, sys, urllib.request
from html.parser import HTMLParser

OWNER = "ojardila"
AUTHOR = {"name": "ojardila", "email": "oscar3425@gmail.com"}
HERE = os.path.dirname(os.path.abspath(__file__))
WF = ".github/workflows/synthetic-monitor.yml"
DRY = "--dry-run" in sys.argv

def gh(*a, input=None, check=True):
    r = subprocess.run(["gh", *a], input=input, capture_output=True, text=True)
    if check and r.returncode:
        raise RuntimeError(f"gh {' '.join(a)}: {r.stderr.strip()}")
    return r

def get_file(repo, path, ref):
    r = gh("api", f"repos/{OWNER}/{repo}/contents/{path}?ref={ref}", check=False)
    return None if r.returncode else base64.b64decode(json.loads(r.stdout)["content"]).decode("utf-8", "replace")

def tree(repo, ref):
    r = gh("api", f"repos/{OWNER}/{repo}/git/trees/{ref}?recursive=1", check=False)
    return [] if r.returncode else [t["path"] for t in json.loads(r.stdout).get("tree", [])]

def public_hosts(repo, ref, paths):
    hosts = []
    for p in paths:
        if not (p.startswith("manifests/") and p.endswith((".yaml", ".yml"))) or "overlays/dev" in p:
            continue
        txt = get_file(repo, p, ref) or ""
        if "kind: HTTPRoute" not in txt:
            continue
        for inline in re.findall(r"hostnames:\s*\[([^\]]*)\]", txt):
            hosts += re.findall(r"[A-Za-z0-9*.-]+\.[A-Za-z]+", inline)
        for block in re.findall(r"hostnames:\s*\n((?:\s+-\s*\S+\s*\n)+)", txt):
            hosts += re.findall(r"-\s*\"?([A-Za-z0-9*.-]+)\"?", block)
    out = []
    for h in hosts:
        if "*" in h or ".int." in h or h.endswith(".local") or h in out:
            continue
        out.append(h)
    return out

class P(HTMLParser):
    def __init__(self):
        super().__init__(); self.t = ""; self.i = False; self.sel = []
    def handle_starttag(self, tag, a):
        a = dict(a)
        if tag == "title": self.i = True
        if a.get("id") and tag in ("main", "section", "header", "nav") and len(self.sel) < 5:
            self.sel.append("#" + a["id"])
        if tag in ("header", "main", "footer", "nav") and tag not in self.sel:
            self.sel.append(tag)
    def handle_endtag(self, tag):
        if tag == "title": self.i = False
    def handle_data(self, d):
        if self.i: self.t += d

def make_config(repo, url):
    lines = [f"# Synthetic monitor for {repo}. Generated by ojardila/site-monitor.",
             "# Review: tighten title/contains/selectors/links, then drop `revalidate`.",
             f"name: {url.split('/')[2]}", f"url: {url}", "status: 200", "revalidate: true"]
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "ojardila-site-monitor/1.0"})
        with urllib.request.urlopen(req, timeout=20) as r:
            p = P(); p.feed(r.read(3_000_000).decode("utf-8", "replace"))
        if p.t.strip():
            lines.append("title: '" + re.escape(p.t.strip()[:40]).replace("'", "") + "'")
        if p.sel:
            lines.append("selectors:"); lines += [f"  - '{s}'" for s in p.sel]
    except Exception as e:
        lines.append(f"# Site did not answer at generation time ({type(e).__name__}): status/5xx only.")
    return "\n".join(lines) + "\n"

def put(repo, path, content, ref, msg):
    if DRY:
        print(f"  DRY: would commit {path}"); return
    body = {"message": msg, "content": base64.b64encode(content.encode()).decode(),
            "branch": ref, "author": AUTHOR, "committer": AUTHOR}
    gh("api", "-X", "PUT", f"repos/{OWNER}/{repo}/contents/{path}", "--input", "-", input=json.dumps(body))

def main():
    template = open(os.path.join(HERE, "..", "templates", "synthetic-monitor.yml")).read()
    repos = json.loads(gh("repo", "list", OWNER, "-L", "500", "--no-archived", "--source",
                          "--json", "name,repositoryTopics,defaultBranchRef,homepageUrl").stdout)
    report = []
    for r in repos:
        name = r["name"]
        if name == "site-monitor":
            continue
        topics = [t["name"] for t in (r.get("repositoryTopics") or [])]
        ref = (r.get("defaultBranchRef") or {}).get("name")
        if "no-monitor" in topics or not ref:
            continue
        paths = tree(name, ref)
        hosts = public_hosts(name, ref, paths)
        if "website" not in topics and not hosts:
            continue
        has_cfg, has_wf = "monitor.yaml" in paths, WF in paths
        status = "compliant" if has_cfg and has_wf else "provisioned"
        if status == "provisioned":
            url = r.get("homepageUrl") or (f"https://{hosts[0]}/" if hosts else None)
            if not url:
                report.append(f"{name}: SKIPPED (topic website but no homepage/hostname)"); continue
            print(f"{name}: adding monitor for {url}")
            if not has_cfg:
                put(name, "monitor.yaml", make_config(name, url), ref, "Add synthetic monitor config")
            if not has_wf:
                put(name, WF, template, ref, "Add synthetic monitor workflow")
        have = gh("secret", "list", "-R", f"{OWNER}/{name}", "--json", "name", "-q", ".[].name", check=False).stdout.split()
        for s in ("TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID"):
            if s in have:
                continue
            if os.environ.get(s) and not DRY:
                gh("secret", "set", s, "-R", f"{OWNER}/{name}", "--body", os.environ[s]); status += f", {s} set"
            else:
                status += f", MISSING {s}"
        if status.startswith("provisioned") and not DRY:
            gh("workflow", "run", "synthetic-monitor.yml", "-R", f"{OWNER}/{name}", check=False)
        report.append(f"{name}: {status}")
    print("\n".join(report))
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        open(os.environ["GITHUB_STEP_SUMMARY"], "a").write("\n".join(f"- {l}" for l in report) + "\n")

if __name__ == "__main__":
    main()
